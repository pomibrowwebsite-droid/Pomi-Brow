import { defineField, defineType } from "sanity";
import { sectionsField } from "./sections";
import { photoField } from "./photo";
import { fits, noPlaceholder } from "./rules";

export const learnArticle = defineType({
  name: "learnArticle",
  title: "Learn article",
  type: "document",
  groups: [
    { name: "text", title: "Words", default: true },
    { name: "sections", title: "Page sections" },
    { name: "photos", title: "Photos" },
    { name: "settings", title: "Settings" },
  ],
  validation: noPlaceholder(),
  fields: [
    defineField({ name: "title", title: "Question or title", type: "string", group: "text", validation: fits(70, { required: true }) }),
    defineField({
      name: "summary",
      title: "Short answer",
      type: "text",
      rows: 3,
      group: "text",
      description: "Two or three sentences. Shown on the article's card, and as the answer when it appears as a question on the home page.",
      validation: fits(260),
    }),
    defineField({
      name: "body",
      title: "Article text",
      type: "array",
      group: "text",
      of: [{ type: "block" }, { type: "image", options: { hotspot: true } }],
      description: "Used only when the article has no page sections.",
    }),
    { ...sectionsField, group: "sections" },
    photoField("cover", "Main photo", "Shown on the article's card and at the top of the article.", "photos"),
    defineField({
      name: "lead",
      title: "Top photo when there's no main photo",
      type: "imageSlot",
      group: "photos",
    }),
    defineField({
      name: "slug",
      title: "Page address",
      type: "slug",
      group: "settings",
      options: { source: "title" },
      validation: (r) => r.required().error("Click “Generate” to make the page address."),
      description: "The article lives at /learn/<this>. Click Generate for a new article. Don't change it for an existing one: links and Google results point at it.",
    }),
    defineField({
      name: "relatedService",
      title: "About which service?",
      type: "reference",
      group: "settings",
      to: [{ type: "service" }],
      description: "Optional. Lists the article on that service's page.",
    }),
    defineField({
      name: "serviceGuide",
      title: "This is the main guide to that service",
      type: "boolean",
      group: "settings",
      description: "Lists it first on the service's page.",
      initialValue: false,
    }),
    defineField({
      name: "showAsFaq",
      title: "Show as a question on the home page",
      type: "boolean",
      group: "settings",
      description: "The home page shows up to five.",
      initialValue: false,
    }),
    defineField({
      name: "order",
      title: "Position in lists",
      type: "number",
      group: "settings",
      description: "Lower numbers come first on the Learn page and in the footer: 10, 20, 30…",
    }),
    defineField({
      name: "seoTitle",
      title: "Title on Google",
      type: "string",
      group: "settings",
      description: "Leave empty for “<title> | Pomi B. Brow Studio”.",
      validation: fits(70),
    }),
  ],
  orderings: [{ title: "List order", name: "order", by: [{ field: "order", direction: "asc" }] }],
  preview: { select: { title: "title", subtitle: "summary", media: "cover" } },
});
