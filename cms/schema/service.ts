import { defineField, defineType } from "sanity";
import { galleryRefField, photoField } from "./photo";
import { fits, noPlaceholder } from "./rules";

export const service = defineType({
  name: "service",
  title: "Service",
  type: "document",
  groups: [
    { name: "text", title: "Words", default: true },
    { name: "price", title: "Price" },
    { name: "photos", title: "Photos" },
    { name: "google", title: "Google" },
  ],
  validation: noPlaceholder(),
  fields: [
    defineField({ name: "title", title: "Service name", type: "string", group: "text", validation: fits(40, { required: true }) }),
    defineField({
      name: "summary",
      title: "One-line summary",
      type: "text",
      rows: 2,
      group: "text",
      description: "Shown on the price list card and at the top of the service page.",
      validation: fits(150),
    }),
    defineField({
      name: "description",
      title: "More about this service",
      type: "array",
      of: [{ type: "block" }],
      group: "text",
      description: "Optional longer text for the service page.",
    }),
    defineField({
      name: "category",
      type: "string",
      group: "text",
      options: { list: ["Eyebrows", "Eyes", "Lips", "Hair", "Maintenance", "Correction"], layout: "radio" },
      description: "Eyebrows, Eyes, Lips and Hair get their own card on the home page. Maintenance and Correction are listed together in the “Touch-ups and correction” card.",
      validation: (r) => r.required().error("Choose a category."),
    }),
    defineField({
      name: "showOnHome",
      title: "Show on the home page price list",
      type: "boolean",
      group: "text",
      initialValue: true,
    }),
    defineField({
      name: "slug",
      title: "Page address",
      type: "slug",
      group: "google",
      options: { source: "title" },
      validation: (r) => r.required().error("Click “Generate” to make the page address."),
      description:
        "The page lives at /services/<this>. Click Generate for a new service. Don't change it for an existing one: links and Google results point at it.",
    }),
    defineField({
      name: "price",
      title: "Price (USD)",
      type: "number",
      group: "price",
      validation: (r) => r.required().error("Enter the price.").min(0),
    }),
    defineField({
      name: "priceUnit",
      title: "Price per",
      type: "string",
      group: "price",
      description: "Leave empty for a flat price. Write “hr” for hourly or “session” for per session.",
      validation: fits(10),
    }),
    defineField({
      name: "touchUpPrice",
      title: "Six-week touch-up price (USD)",
      type: "number",
      group: "price",
      description: "Leave empty when the service has no touch-up.",
      validation: (r) => r.min(0),
    }),
    defineField({
      name: "priceNote",
      title: "Short note beside the price",
      type: "string",
      group: "price",
      description: "e.g. “up to 4 sessions” or “existing clients”.",
      validation: fits(24),
    }),
    defineField({
      name: "order",
      title: "Position in the price list",
      type: "number",
      group: "price",
      description: "Lower numbers come first: 10, 20, 30… To put a service between two others, use a number in between, like 25.",
      validation: (r) => r.required().error("Give it a position, e.g. 100 to put it last."),
    }),
    photoField("cover", "Main photo", "The one photo for this service on the home price list and at the top of its page.", "photos"),
    defineField({
      name: "gallery",
      title: "Healed results",
      type: "array",
      group: "photos",
      description: "The photos on the service page, in this order. Drag to reorder.",
      options: { layout: "grid" },
      of: [
        {
          type: "image",
          options: { hotspot: true },
          fields: [
            galleryRefField,
            defineField({
              name: "alt",
              title: "Describe the photo",
              type: "string",
              description: "Leave empty for “<service> by Pomi B. Brow Studio, healed result”.",
              validation: fits(140),
            }),
            defineField({ name: "caption", type: "string", description: "e.g. Healed six weeks", validation: fits(30) }),
            defineField({ name: "beforeAfter", title: "Before / after photo", type: "boolean" }),
          ],
        },
      ],
    }),
    defineField({
      name: "seoTitle",
      title: "Title on Google",
      type: "string",
      group: "google",
      description: "Leave empty for “<service> in Tustin, near Irvine | Pomi B. Brow Studio”.",
      validation: fits(70),
    }),
  ],
  orderings: [{ title: "Price list order", name: "order", by: [{ field: "order", direction: "asc" }] }],
  preview: {
    select: { title: "title", category: "category", price: "price", media: "cover" },
    prepare: ({ title, category, price, media }) => ({ title, subtitle: [category, price != null ? `$${price}` : null].filter(Boolean).join(" · "), media }),
  },
});
